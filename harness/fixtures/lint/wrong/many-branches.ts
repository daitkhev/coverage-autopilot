export function expand(letter: string): string {
  if (letter === 'a') {
    return 'aa';
  }
  if (letter === 'b') {
    return 'bb';
  }
  if (letter === 'c') {
    return 'cc';
  }
  if (letter === 'd') {
    return 'dd';
  }
  if (letter === 'e') {
    return 'ee';
  }
  if (letter === 'f') {
    return 'ff';
  }
  if (letter === 'g') {
    return 'gg';
  }
  if (letter === 'h') {
    return 'hh';
  }
  return letter;
}
