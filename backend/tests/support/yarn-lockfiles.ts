/** A package as yarn 1 names it in an entry: quoted when it starts with `@`. */
function descriptorOf(name: string, range: string): string {
  return name.startsWith('@') ? `"${name}@${range}"` : `${name}@${range}`;
}

/**
 * A `yarn.lock` of yarn 1 with each package a dependency of the project
 * at `^version`, in an entry that resolves a second range as well, after
 * an entry of the same package at another version that another package
 * asks for.
 */
export function classicLockfileOf(
  versions: Readonly<Record<string, string>>,
): string {
  const entries = Object.entries(versions).map(
    ([name, version]) =>
      `${descriptorOf(name, '^29.0.0')}:\n  version "29.7.0"\n\n` +
      `${descriptorOf(name, `^${version}`)}, ${descriptorOf(name, `~${version}`)}:\n` +
      `  version "${version}"\n` +
      `  resolved "https://registry.yarnpkg.com/${name}/-/x-${version}.tgz#0a1b"\n` +
      '  integrity sha512-oKnb\n',
  );
  return [
    '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n' +
      '# yarn lockfile v1\n\n',
    ...entries,
  ].join('\n');
}
